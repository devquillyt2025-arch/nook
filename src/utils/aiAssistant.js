/**
 * aiAssistant.js
 * 
 * Handles communication with the Gemini API using the native fetch API.
 */
import { buildAiContext } from './aiContext';

export async function askAssistant(chatHistory, newQuestion) {
  // The user's own key, from Settings (per device, never synced). Deliberately NOT a VITE_ env var:
  // Vite inlines those into the public bundle, shipping the key to every visitor.
  const apiKey = localStorage.getItem('nook_ai_api_key');
  
  if (!apiKey) {
    throw new Error('API key is missing. Please add your Gemini API key in the Settings tab.');
  }

  // Build the system context
  const context = buildAiContext();
  const systemPrompt = `You are Nook's AI Assistant. You help the user manage their personal productivity. 
You have access to the user's current data below.
Use this data to answer their questions. Be concise and helpful.

${context}`;

  // Format messages for Gemini API
  // Gemini expects: { contents: [{ role: 'user'|'model', parts: [{text: '...'}] }] }
  
  // We'll inject the system prompt into the first user message, since the standard v1beta 
  // chat endpoint sometimes handles system instructions differently depending on the exact version. 
  // Prepended context is robust.
  
  const contents = chatHistory.map(msg => ({
    role: msg.role === 'assistant' ? 'model' : 'user',
    parts: [{ text: msg.content }]
  }));

  // Append the new question, with system prompt if it's the very first message
  const userText = contents.length === 0 
    ? `${systemPrompt}\n\nUser Question: ${newQuestion}`
    : newQuestion;

  contents.push({
    role: 'user',
    parts: [{ text: userText }]
  });

  // The key goes in a header, not the query string, so it stays out of URLs, logs and referrers.
  const headers = { 'Content-Type': 'application/json', 'x-goog-api-key': apiKey };
  let url = 'https://generativelanguage.googleapis.com/v1beta/models/gemini-3.7-flash:generateContent';

  let response = await fetch(url, {
    method: 'POST',
    headers,
    body: JSON.stringify({
      contents,
      generationConfig: {
        temperature: 0.7,
        maxOutputTokens: 1024,
      }
    })
  });

  if (!response.ok) {
    const errorData = await response.json().catch(() => ({}));
    if (errorData.error?.message?.includes('not found') || errorData.error?.message?.includes('high demand') || errorData.error?.message?.includes('overloaded')) {
      // Fallback if 3.7 isn't found
      url = 'https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent';
      response = await fetch(url, {
        method: 'POST',
        headers,
        body: JSON.stringify({ contents, generationConfig: { temperature: 0.7, maxOutputTokens: 1024 } })
      });
      if (!response.ok) {
        const fallbackError = await response.json().catch(() => ({}));
        throw new Error(fallbackError.error?.message || 'Failed to communicate with AI Assistant.');
      }
    } else {
      throw new Error(errorData.error?.message || 'Failed to communicate with AI Assistant.');
    }
  }

  const data = await response.json();
  
  if (data.candidates && data.candidates.length > 0) {
    const text = data.candidates[0].content.parts.map(p => p.text).join('');
    return text;
  }
  
  throw new Error('No response generated by AI.');
}
